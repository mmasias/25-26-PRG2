class Fraccion {
    private int numerador;
    private int denominador;
    
    public Fraccion(int numerador, int denominador)
    {
        numerador = this.numerador;
        denominador = this.denominador;
    }
     
    public Fraccion(int numerador)
    {
        this(numerador, 1);
    }

    public Fraccion()
    {
        this(1,1);
    }

    
}
